/**
 * A tiny, dependency-free finite-state-machine definition shared by the API,
 * the SPA and the MCP tools.
 *
 * Every persisted lifecycle in seald (an envelope's `status`, a seal job's
 * `status`, a bulk batch, …) is declared once with {@link defineMachine}.
 * Code then asks the machine instead of comparing status strings:
 *
 * - writes guard on {@link Machine.sources} (`WHERE status IN (…)`), so the
 *   SQL and the declared table cannot drift;
 * - services gate requests with {@link Machine.can} / {@link Machine.allows};
 * - the SPA shows only the actions {@link Machine.allowedActions} returns;
 * - agents read the same table (`docs/state-machines.md`, generated by
 *   {@link toMermaid} and pinned by a test).
 *
 * The machine describes what is *allowed*. Concurrency is still handled by
 * the row-conditional UPDATE: the guard is `status IN machine.sources(e)`.
 */

export interface TransitionSpec<S extends string> {
  /** States the event may fire from. */
  readonly from: readonly S[];
  /** State the event moves to. */
  readonly to: S;
  /** One line: who fires it and why. Rendered into docs and agent output. */
  readonly description: string;
}

export interface MachineDefinition<S extends string, E extends string, A extends string> {
  /** Stable id, e.g. `envelope`. */
  readonly id: string;
  /** Where the state lives, e.g. `envelopes.status`. */
  readonly storedIn: string;
  readonly description: string;
  readonly states: readonly S[];
  readonly initial: S;
  /** Other states a row may be created in (a bulk row inserted as `invalid`). */
  readonly entry?: readonly S[];
  /** States no event leaves. Checked at definition time. */
  readonly terminal: readonly S[];
  readonly transitions: { readonly [K in E]: TransitionSpec<S> };
  /**
   * Actions that do not change the state but are only allowed in some
   * states (edit a draft, remind a signer, download the sealed PDF).
   */
  readonly actions?: {
    readonly [K in A]: { readonly in: readonly S[]; readonly description: string };
  };
}

/**
 * Lookups take `S | string` so a value read from a row or the wire can be
 * asked directly; an unknown state answers `false` / `[]`.
 */
export interface Machine<
  S extends string,
  E extends string,
  A extends string = never,
> extends MachineDefinition<S, E, A> {
  /** Whether `event` may fire from `state`. */
  can(state: S | (string & {}), event: E): boolean;
  /** The state `event` leads to from `state`, or `null` when it may not fire. */
  next(state: S | (string & {}), event: E): S | null;
  /** Like {@link next} but throws {@link IllegalTransitionError}. */
  transition(state: S, event: E): S;
  /** States `event` may fire from: the `WHERE status IN (…)` of a guarded write. */
  sources(event: E): readonly S[];
  /** Events that may fire from `state`, in declaration order. */
  events(state: S | (string & {})): readonly E[];
  isTerminal(state: S | (string & {})): boolean;
  /** Whether the state-gated `action` is allowed in `state`. */
  allows(state: S | (string & {}), action: A): boolean;
  /** Actions allowed in `state`, in declaration order. */
  allowedActions(state: S | (string & {})): readonly A[];
  /** States `action` is allowed in: the `WHERE status IN (…)` of a gated write. */
  statesAllowing(action: A): readonly S[];
  /** Type guard for a value read from the database or the wire. */
  isState(value: unknown): value is S;
}

export class IllegalTransitionError extends Error {
  constructor(
    readonly machine: string,
    readonly state: string,
    readonly event: string,
  ) {
    super(`${machine}: event "${event}" is not allowed from state "${state}"`);
    this.name = 'IllegalTransitionError';
  }
}

function fail(id: string, message: string): never {
  throw new Error(`defineMachine(${id}): ${message}`);
}

/**
 * Declare a machine. Throws at module load when the table is inconsistent
 * (unknown state, a terminal state with an outgoing event, an unreachable
 * state), so a bad edit fails every test run immediately.
 */
export function defineMachine<
  const S extends string,
  const E extends string,
  const A extends string = never,
>(def: MachineDefinition<S, E, A>): Machine<S, E, A> {
  const states = new Set<string>(def.states);
  if (states.size !== def.states.length) fail(def.id, 'duplicate state');
  if (!states.has(def.initial)) fail(def.id, `unknown initial state "${def.initial}"`);
  for (const t of def.terminal) {
    if (!states.has(t)) fail(def.id, `unknown terminal state "${t}"`);
  }
  const terminal = new Set<string>(def.terminal);
  const eventNames = Object.keys(def.transitions) as E[];
  for (const e of eventNames) {
    const spec = def.transitions[e];
    if (spec.from.length === 0) fail(def.id, `event "${e}" has no source state`);
    if (!states.has(spec.to)) fail(def.id, `event "${e}" targets unknown state "${spec.to}"`);
    for (const f of spec.from) {
      if (!states.has(f)) fail(def.id, `event "${e}" fires from unknown state "${f}"`);
      if (terminal.has(f)) fail(def.id, `event "${e}" leaves terminal state "${f}"`);
    }
  }
  const actionNames = (def.actions ? Object.keys(def.actions) : []) as A[];
  for (const a of actionNames) {
    for (const s of def.actions![a].in) {
      if (!states.has(s)) fail(def.id, `action "${a}" allowed in unknown state "${s}"`);
    }
  }
  for (const e of def.entry ?? []) {
    if (!states.has(e)) fail(def.id, `unknown entry state "${e}"`);
  }
  // Every state must be reachable from the initial (or an entry) state.
  const reached = new Set<string>([def.initial, ...(def.entry ?? [])]);
  let grew = true;
  while (grew) {
    grew = false;
    for (const e of eventNames) {
      const spec = def.transitions[e];
      if (!reached.has(spec.to) && spec.from.some((f) => reached.has(f))) {
        reached.add(spec.to);
        grew = true;
      }
    }
  }
  for (const s of def.states) {
    if (!reached.has(s)) fail(def.id, `state "${s}" is unreachable from "${def.initial}"`);
  }

  const can = (state: string, event: E): boolean =>
    (def.transitions[event]?.from as readonly string[] | undefined)?.includes(state) ?? false;
  const allows = (state: string, action: A): boolean =>
    (def.actions?.[action]?.in as readonly string[] | undefined)?.includes(state) ?? false;

  return Object.freeze({
    ...def,
    can,
    next: (state: string, event: E): S | null =>
      can(state, event) ? def.transitions[event].to : null,
    transition(state: S, event: E): S {
      if (!can(state, event)) throw new IllegalTransitionError(def.id, state, event);
      return def.transitions[event].to;
    },
    sources: (event: E): readonly S[] => def.transitions[event].from,
    events: (state: string): readonly E[] => eventNames.filter((e) => can(state, e)),
    isTerminal: (state: string): boolean => terminal.has(state),
    allows,
    allowedActions: (state: string): readonly A[] => actionNames.filter((a) => allows(state, a)),
    statesAllowing: (action: A): readonly S[] => def.actions?.[action]?.in ?? [],
    isState: (value: unknown): value is S => typeof value === 'string' && states.has(value),
  });
}

/**
 * The declared table of any machine, without its lookups: what docs and
 * lists of heterogeneous machines need.
 */
export interface MachineSummary {
  readonly id: string;
  readonly storedIn: string;
  readonly description: string;
  readonly initial: string;
  readonly entry?: readonly string[] | undefined;
  readonly terminal: readonly string[];
  readonly transitions: Readonly<Record<string, TransitionSpec<string>>>;
  readonly actions?:
    | Readonly<Record<string, { readonly in: readonly string[]; readonly description: string }>>
    | undefined;
}

/**
 * Mermaid `stateDiagram-v2` for a machine. Rendered by GitHub in
 * `docs/state-machines.md`; a test keeps that file in sync.
 */
export function toMermaid(m: MachineSummary): string {
  const lines = ['stateDiagram-v2', `  [*] --> ${m.initial}`];
  for (const e of m.entry ?? []) lines.push(`  [*] --> ${e}`);
  for (const [event, spec] of Object.entries(m.transitions)) {
    for (const from of spec.from) lines.push(`  ${from} --> ${spec.to}: ${event}`);
  }
  for (const t of m.terminal) lines.push(`  ${t} --> [*]`);
  return lines.join('\n');
}

/** Markdown section for one machine: diagram, transition table, gated actions. */
export function toMarkdown(m: MachineSummary): string {
  const out: string[] = [
    `## \`${m.id}\``,
    '',
    m.description,
    '',
    `Stored in \`${m.storedIn}\`. Initial: ${[m.initial, ...(m.entry ?? [])]
      .map((s) => `\`${s}\``)
      .join(', ')}. Terminal: ${
      m.terminal.length ? m.terminal.map((t) => `\`${t}\``).join(', ') : 'none'
    }.`,
    '',
    '```mermaid',
    toMermaid(m),
    '```',
    '',
    '| Event | From | To | Meaning |',
    '| --- | --- | --- | --- |',
  ];
  for (const [event, spec] of Object.entries(m.transitions)) {
    out.push(
      `| \`${event}\` | ${spec.from.map((f) => `\`${f}\``).join(', ')} | \`${spec.to}\` | ${spec.description} |`,
    );
  }
  const actions = m.actions ? Object.entries(m.actions) : [];
  if (actions.length) {
    out.push('', '| Action | Allowed in | Meaning |', '| --- | --- | --- |');
    for (const [action, spec] of actions) {
      out.push(
        `| \`${action}\` | ${spec.in.map((s) => `\`${s}\``).join(', ')} | ${spec.description} |`,
      );
    }
  }
  return out.join('\n');
}
